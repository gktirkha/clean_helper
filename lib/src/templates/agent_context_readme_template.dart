import '../functions/agent_context/agent_command_docs.dart';
import '../functions/agent_context/agent_context_info.dart';
import '../functions/agent_context/project_agent_rules.dart';

/// `.agents/README.md`: entry point of the generated AI context.
///
/// [projectRules] are the project-owned files in `.agents/`; each gets a row
/// in the reading order after `architecture.md`.
String agentContextReadmeTemplate(
  AgentContextInfo info,
  String version, {
  List<ProjectAgentRule> projectRules = const [],
}) {
  final layout = info.apps.isEmpty
      ? 'A single Flutter app (`${info.projectName}`).'
      : 'A pub-workspace monorepo (`${info.projectName}`) with apps '
            '${info.apps.map((a) => '`$a`').join(', ')} and shared packages in '
            '`${info.foundationDir}/`.';
  final commands = agentCommandDocs
      .map((c) => '| [`${c.name}`](commands/${c.name}.md) | ${c.summary} |')
      .join('\n');
  final projectRows = projectRules
      .map((r) => '| [`${r.fileName}`](${r.fileName}) | ${r.title} |\n')
      .join();
  final projectNote = projectRules.isEmpty
      ? ''
      : '''


Other `*.md` files in `.agents/` are project rules: clean-helper never
overwrites them, and where they conflict with the generated files they win.''';
  return '''
# AI context for ${info.projectName}

Generated by [clean_helper](https://pub.dev/packages/clean_helper) $version
(`clean-helper add-agent-context`). Rerunning it keeps existing files;
`--overwrite` refreshes the generated ones. Project-specific rules go in their
own `.agents/*.md` files, which are never changed.

$layout The code follows Clean Architecture and is scaffolded by the
`clean-helper` CLI. Use its commands to add features, repositories and
entities, so new code keeps the same shape.$projectNote

Read, in order:

| File | For |
|---|---|
| [`rules.md`](rules.md) | Hard rules — read before changing anything |
| [`architecture.md`](architecture.md) | How the project is laid out and wired |
$projectRows| `commands/<command>.md` | When and how to run each clean-helper command |

## Commands

| Command | Does |
|---|---|
$commands
''';
}
